// writes src/scripts/utils/buildInfo.ts: where the build comes from, shown next to the version number in the app.
// Releases (tag builds and a clean main) show only the version, a build from another branch shows its name (e.g. the
// worktree of a feature) and local changes add a "*".
import { execSync } from "node:child_process"
import { writeFileSync } from "node:fs"

const git = (command) => {
	try {
		return execSync("git " + command, { stdio: ["ignore", "pipe", "ignore"] })
			.toString()
			.trim()
	} catch {
		return ""
	}
}

const branch = git("rev-parse --abbrev-ref HEAD")
const dirty = git("status --porcelain --untracked-files=no") !== ""
const name = branch && branch !== "HEAD" ? branch : ""
const info = name == "main" && !dirty ? "" : name + (dirty ? "*" : "")

writeFileSync(
	new URL("../src/scripts/utils/buildInfo.ts", import.meta.url),
	`// generated by scripts/buildInfo.mjs, do not edit\nexport const buildInfo = ${JSON.stringify(info)}\n`
)
